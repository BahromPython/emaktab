# ── INJECTION LOGIC ───────────────────────────────────────────────────────────

def fmt_q(q):
    text  = q['q'].replace("'", "`")
    opts  = ', '.join(f"'{o.replace(chr(39), chr(96))}'" for o in q['opts'])
    return f"    {{'q':'{text}', 'opts':[{opts}], 'ans':{q['ans']}}}"

def build_js_block(exam_id, questions):
    lines = [f"  '{exam_id}': ["]
    lines += [fmt_q(q) + ',' for q in questions]
    lines.append('  ],')
    return '\n'.join(lines)

def replace_exam(html, exam_id, new_block):
    # Find the exam entry by id and replace from '[' to matching '],'
    pattern = re.compile(r"(\s*'" + re.escape(exam_id) + r"':\s*\[)", re.MULTILINE)
    m = pattern.search(html)
    if not m:
        print(f'  WARN NOT FOUND: {exam_id}')
        return html, False
    start = m.start()
    bracket_open = html.index('[', m.start())
    # Walk to find matching ]
    depth = 1
    i = bracket_open + 1
    while i < len(html) and depth > 0:
        if html[i] == '[':  depth += 1
        elif html[i] == ']': depth -= 1
        i += 1
    # i now points just after the closing ]
    # consume optional comma and newline
    end = i
    if end < len(html) and html[end] == ',':
        end += 1
    return html[:start] + '\n' + new_block + html[end:], True

