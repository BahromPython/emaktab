    html = raw.decode('utf-8')

    # Backup
    backup = HTML_FILE.replace('.html', f'_backup_g14_{datetime.datetime.now().strftime("%Y%m%d_%H%M%S")}.html')
    shutil.copy(HTML_FILE, backup)
    print(f'Backup: Backup: {backup}')

    replaced, skipped = 0, 0
    for exam_id, questions in EXAMS.items():
        new_block = build_js_block(exam_id, questions)
        html, ok = replace_exam(html, exam_id, new_block)
        if ok:
            replaced += 1
            print(f'  OK {exam_id}: {len(questions)} questions')
        else:
            skipped += 1

    with open(HTML_FILE, 'w', encoding='utf-8') as f:
        f.write(html)

    print(f'\nDone! Done! Replaced: {replaced}, Skipped: {skipped}')
    print(f'Saved: Saved: {HTML_FILE}')

